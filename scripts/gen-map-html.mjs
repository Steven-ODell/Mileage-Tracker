// Inlines MapLibre into map/map.html and writes src/generated/mapHtml.ts, so
// the map page works without fetching any script (only tiles need network).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'node_modules/maplibre-gl/dist');
const js = readFileSync(join(dist, 'maplibre-gl.js'), 'utf8').replaceAll('</script', '<\\/script');
const css = readFileSync(join(dist, 'maplibre-gl.css'), 'utf8');
const html = readFileSync(join(root, 'map/map.html'), 'utf8')
  .replace('/*MAPLIBRE_CSS*/', () => css)
  .replace('/*MAPLIBRE_JS*/', () => js);
mkdirSync(join(root, 'src/generated'), { recursive: true });
writeFileSync(
  join(root, 'src/generated/mapHtml.ts'),
  `// Generated by scripts/gen-map-html.mjs from map/map.html. Do not edit.\nexport const MAP_HTML = ${JSON.stringify(html)};\n`
);
console.log(`map html: ${(html.length / 1024).toFixed(0)} KB`);
